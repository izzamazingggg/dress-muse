const amazonImage = (id: string, size = "SX425") =>
  `https://m.media-amazon.com/images/I/${id}._AC_${size}_.jpg`;

const colorHex = (color: string): string => {
  const c = color.toLowerCase();
  if (c.includes("black")) return "#282828";
  if (c.includes("white") || c.includes("off-white")) return "#F0EDE5";
  if (c.includes("navy")) return "#26395B";
  if (c.includes("royal")) return "#416CB0";
  if (c.includes("blue")) return "#789DBF";
  if (c.includes("green") || c.includes("olive")) return "#7B9C7D";
  if (c.includes("burgundy") || c.includes("wine")) return "#763448";
  if (c.includes("maroon")) return "#733847";
  if (c.includes("red")) return "#B34D52";
  if (c.includes("pink") || c.includes("blush") || c.includes("rose"))
    return "#DDA4B6";
  if (c.includes("purple") || c.includes("grape")) return "#9477AC";
  if (c.includes("lavender")) return "#B5A0CC";
  if (c.includes("yellow")) return "#E7CA72";
  if (c.includes("orange") || c.includes("peach")) return "#D99663";
  if (c.includes("coffee") || c.includes("brown")) return "#9A765D";
  if (c.includes("grey") || c.includes("gray")) return "#92969A";
  if (c.includes("champagne") || c.includes("apricot"))
    return "#E8C4A3";
  return "#C9A9A0";
};

type ColorImage = [string, string, string?];

const makeVariants = (
  items: ColorImage[],
  amazonUrl: string,
  defaultSize = "SX425"
) =>
  items.map(([color, imageId, size]) => ({
    color,
    hex: colorHex(color),
    image: amazonImage(imageId, size || defaultSize),
    amazonUrl,
  }));

